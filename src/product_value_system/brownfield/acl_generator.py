_NON_IDENT_RE = re.compile(r"[^A-Za-z0-9_]+")


def _to_pascal_case(raw_name: str) -> str:
    tokens = [t for t in _NON_IDENT_RE.split(raw_name) if t]
    if not tokens:
        return "LegacyModule"
    joined = "".join(tok[0].upper() + tok[1:] for tok in tokens)
    if joined[0].isdigit():
        joined = f"Mod{joined}"
    return joined


def _to_snake_case(raw_name: str) -> str:
    cleaned = _NON_IDENT_RE.sub("_", raw_name).strip("_").lower()
    if not cleaned:
        return "legacy_module"
    if cleaned[0].isdigit() or keyword.iskeyword(cleaned):
        cleaned = f"mod_{cleaned}"
    return cleaned


def _sanitize_param_name(name: str, fallback: str) -> str:
    cleaned = _NON_IDENT_RE.sub("_", name).strip("_")
    if not cleaned or cleaned[0].isdigit() or keyword.iskeyword(cleaned):
        return fallback
    return cleaned


@dataclass
class APIFunctionSpec:
    """Public function signature extracted from a legacy module."""

    name: str
    params: list[str]
    return_type: str = "Any"

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "params": list(self.params),
            "return_type": self.return_type,
        }


