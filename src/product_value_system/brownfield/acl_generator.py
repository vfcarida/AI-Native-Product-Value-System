class ACLGenerator:
    """Generate compilable Python Anti-Corruption Layer adapters for legacy modules."""

    def __init__(self, *, max_methods: int = 12) -> None:
        self.max_methods = max(1, int(max_methods))

    def extract_api(
        self,
        module: Module,
        code_structure: dict[str, Any] | None = None,
        *,
        repo_path: Path | None = None,
    ) -> list[APIFunctionSpec]:
        """Extract public API function signatures from Python files in ``module``."""
        _ = code_structure
        seen: set[str] = set()
        extracted: list[APIFunctionSpec] = []

        if repo_path is not None:
            repo_root = repo_path.resolve()
            for rel_path in module.file_paths:
                if not rel_path.endswith(".py"):
                    continue
                full_path = (repo_root / rel_path).resolve()
                if not full_path.is_relative_to(repo_root) or not full_path.is_file():
                    continue
                try:
                    tree = ast.parse(full_path.read_text(encoding="utf-8", errors="ignore"))
                except (OSError, SyntaxError):
                    continue

                for node in tree.body:
                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        if node.name.startswith("_") or keyword.iskeyword(node.name):
                            continue
                        if node.name in seen:
                            continue
                        seen.add(node.name)
                        params = [
                            _sanitize_param_name(arg.arg, f"arg_{idx}")
                            for idx, arg in enumerate(node.args.args)
                            if arg.arg not in {"self", "cls"}
                        ]
                        extracted.append(APIFunctionSpec(name=node.name, params=params))
                        if len(extracted) >= self.max_methods:
                            return extracted

        if not extracted:
            return [APIFunctionSpec(name="process", params=["request"], return_type="Any")]
        return extracted

    def generate(
        self,
        module: Module,
        code_structure: dict[str, Any] | None = None,
        *,
        repo_path: Path | None = None,
    ) -> str:
        """Render a self-contained, syntax-validated Python ACL module string."""
        functions = self.extract_api(module, code_structure, repo_path=repo_path)
        class_name = f"{_to_pascal_case(module.name)}ACL"
        snake_name = _to_snake_case(module.name)
        safe_module_name = _sanitize_module_label(module.name, snake_name)

        code: str = _ACL_TEMPLATE.render(
            module_name=safe_module_name,
            module_name_repr=repr(safe_module_name),
            class_name=class_name,
            snake_name=snake_name,
            functions=functions,
        )
        ast.parse(code)
        return code
